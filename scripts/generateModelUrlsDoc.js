// scripts/generateModelUrlsDoc.js
//
// Generates docs/model-urls.md from src/utils/modelRegistry.json, so the
// human-readable URL reference cannot drift from the files the offline CLI
// downloads. Run with `yarn update-model-urls` after editing the registry.

const fs = require("node:fs");
const path = require("node:path");
const registry = require("../src/utils/modelRegistry.json");

const OUTPUT = path.join(__dirname, "../docs/model-urls.md");
const KEY_LABELS = {
  modelUrl: "model",
  detectorModelUrl: "detector",
  landmarkModelUrl: "landmark",
  featureVectorURL: "feature vector",
  depthModelUrl: "depth",
  segmentationModelUrl: "segmentation",
};

function render() {
  const lines = [
    "# Model URL reference",
    "",
    "<!-- Generated by scripts/generateModelUrlsDoc.js from src/utils/modelRegistry.json. Do not edit by hand. -->",
    "",
    "Where `ml5 cache prefetch` downloads each model from, and the folder inside `ml5-models/<model>/` it is saved to.",
    "",
    "For a beginner-friendly walkthrough with manual download instructions, see [`manual-model-setup/where-to-download-models.md`](./manual-model-setup/where-to-download-models.md).",
    "",
    "TensorFlow.js sources are folders: append `/model.json` to download the model file, then download each weight file it lists from the same folder. For `tfhub.dev` and `kaggle.com` sources, also add `?tfjs-format=file` to the end of every file URL.",
    "",
    "A source that ends in `.json` is the model file itself. Save it as `model.json`; its weight files are in the same remote folder.",
  ];
  for (const name of Object.keys(registry.models)) {
    const model = registry.models[name];
    lines.push(
      "",
      `## ${model.label} (\`${name}\`)`,
      "",
      "### TensorFlow.js",
      "",
      "| Variant | Part | Local folder | Source |",
      "| --- | --- | --- | --- |"
    );
    for (const variant of Object.keys(model.variants)) {
      const parts = model.variants[variant].tfjs || {};
      const mark = model.defaultVariants.includes(variant) ? " (default)" : "";
      for (const key of Object.keys(parts)) {
        // Files such as metadata.json sit next to model.json, remotely and locally.
        const extra = (parts[key].extraFiles || [])
          .map((file) => `, plus \`${file}\``)
          .join("");
        lines.push(
          `| \`${variant}\`${mark} | ${KEY_LABELS[key] || key}${extra} | \`${
            parts[key].path
          }/\` | ${parts[key].url} |`
        );
      }
    }
    if (model.mediapipe) {
      const { package: pkg, version, shared } = model.mediapipe;
      const base = `https://cdn.jsdelivr.net/npm/${pkg}@${version}`;
      lines.push(
        "",
        "### MediaPipe",
        "",
        `Package \`${pkg}@${version}\`. Files are saved to \`mediapipe/\` and are available at \`${base}/<file>\`.`,
        "",
        "Every variant needs:",
        ""
      );
      shared.forEach((file) => lines.push(`- \`${file}\``));
      const extras = Object.keys(model.variants).filter(
        (variant) => (model.variants[variant].mediapipe || []).length > 0
      );
      if (extras.length > 0) {
        lines.push("", "Plus one file per variant:", "");
        extras.forEach((variant) =>
          lines.push(
            `- \`${variant}\`: ${model.variants[variant].mediapipe
              .map((file) => `\`${file}\``)
              .join(", ")}`
          )
        );
      }
    }
  }
  return `${lines.join("\n")}\n`;
}

const content = render();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
  if (current !== content) {
    console.error(
      "docs/model-urls.md is out of date. Run: yarn update-model-urls"
    );
    process.exit(1);
  }
  console.log("docs/model-urls.md is up to date.");
} else {
  fs.writeFileSync(OUTPUT, content);
  console.log("Wrote docs/model-urls.md");
}
